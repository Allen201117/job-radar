"""公司名归属核验：防「同名子串张冠李戴」。

为何：国聘/搜索类源按关键词返回的是**法人实体全称**，朴素子串匹配会把无关公司抓进来——
2026-07-26 live 实测：搜「中通」命中「北京华晋中通电力工程设计有限公司」（不是中通快递）、
搜「绿城」命中「中交城投绿城（广东）城市运营管理有限公司」、搜「华图」命中「山东中卓华图教育…」。
这些一旦入库就是张冠李戴，直接违反 CLAUDE.md「jd_url / 归属准确性高于一切」。

规则：token 必须出现在公司名**开头**，或只被「地名前缀」隔开。
  ✅ 陕西圆通速递（圆通 前面只有省名）        ✅ 北京京东方松彩创新（京东方 前面只有市名）
  ✅ 泰康人寿保险…天津分公司（token 在开头）   ❌ 北京华晋中通电力（中通 前面还有「华晋」）
  ❌ 中交城投绿城（绿城 前面还有「中交城投」）  ❌ 山东中卓华图教育（华图 前面还有「中卓」）
"""
import re

_PLACES = (
    "北京|上海|天津|重庆|广东|广州|深圳|珠海|佛山|东莞|中山|惠州|汕头|江苏|南京|苏州|无锡|常州|南通|徐州|"
    "浙江|杭州|宁波|温州|绍兴|嘉兴|金华|台州|山东|济南|青岛|烟台|潍坊|临沂|淄博|河北|石家庄|唐山|保定|"
    "河南|郑州|洛阳|湖北|武汉|宜昌|襄阳|湖南|长沙|株洲|四川|成都|绵阳|陕西|西安|辽宁|沈阳|大连|"
    "吉林|长春|黑龙江|哈尔滨|安徽|合肥|芜湖|福建|厦门|福州|泉州|江西|南昌|山西|太原|云南|昆明|"
    "贵州|贵阳|广西|南宁|柳州|海南|三亚|海口|甘肃|兰州|新疆|乌鲁木齐|内蒙古|呼和浩特|包头|"
    "宁夏|银川|青海|西宁|西藏|拉萨|香港|澳门|中国|华北|华东|华南|华中|西南|西北|东北"
)
_PREFIX_RE = re.compile(rf"^(?:{_PLACES})?(?:省|市|自治区|特别行政区)?")


def company_name_matches(company_name: str, token: str) -> bool:
    """`company_name` 是否可信地属于 `token` 指代的公司（见模块 docstring 的规则）。"""
    name = (company_name or "").strip()
    tok = (token or "").strip()
    if not name or not tok or tok not in name:
        return False
    idx = name.index(tok)
    if idx == 0:
        return True
    return bool(_PREFIX_RE.fullmatch(name[:idx]))
