// override 单条是否命中公司名。
// 纯 ASCII 的 key 必须**成词**，中文 key 用 substring。
// ⚠️ 为什么英文要词边界：`["abb","制造/工业"]` 会吃掉 "雅培 Abbott" 的单词内部
// （live 实测雅培 3431 个在招岗被判成制造/工业）。中文没有词边界概念，只能靠下面的最长匹配。
function overrideHits(text, key) {
  if (/^[a-z0-9][a-z0-9 .&-]*$/.test(key)) {
    const escaped = key.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    return new RegExp(`(?<![a-z0-9])${escaped}(?![a-z0-9])`, "i").test(text);
  }
  return text.includes(key);
}

// 公司 → 行业类目（或 null=判不出）。
function classifyCompanyIndustry(company) {
  const text = normalizeCompany(company);
  if (!text) return null;
  // ⚠️ 取**最长**命中，不是数组顺序里第一个命中：短品牌名会吃掉带它的长公司名
  // （"京东"吃"京东方"/"京东物流"、"网易"吃"网易云音乐"/"网易有道"、"腾讯"吃"腾讯音乐"）。
  // 与 crawler/must_apply.resolve_owner 同一个病根、同一个解法（清单名⊂库里名时最长者胜）。
  let best = null;
  for (const [name, cat] of COMPANY_OVERRIDES) {
    const key = normalizeCompany(name);
    if (!overrideHits(text, key)) continue;
    if (!best || key.length > best.key.length) best = { key, cat };
  }
  if (best) return best.cat;
  for (const [cat, rule] of INDUSTRY_KEYWORD_RULES) {
    if (rule.test(text)) return cat;
  }
  return null;
}

